/// Goal JSON shaped like `app/views/api/v1/goals/_goal.json.jbuilder`.
Map<String, dynamic> goalJson(
  String id, {
  String name = 'Emergency fund',
  String state = 'active',
  String status = 'on_track',
  String? displayStatus,
  String kind = 'one_off',
  String? targetDate = '2027-04-30',
  int? daysLeft = 168,
  num? monthsRemaining = 5.5,
  int progress = 62,
  String current = '\$3,100.00',
  int currentCents = 310000,
  String target = '\$5,000.00',
  int targetCents = 500000,
  String? callout,
  String? catchUp,
  int catchUpCents = 0,
  List<Map<String, dynamic>> pledges = const [],
  List<Map<String, dynamic>>? linked,
  String? notes,
}) =>
    {
      'id': id,
      'name': name,
      'kind': kind,
      'target_mode': 'fixed',
      'target_months': null,
      'state': state,
      'status': status,
      'display_status': displayStatus ?? (state == 'active' ? status : state),
      'color': '#4da568',
      'icon': 'piggy-bank',
      'notes': notes,
      'currency': 'USD',
      'target_date': targetDate,
      'days_left': daysLeft,
      'months_remaining': monthsRemaining,
      'target_amount': target,
      'target_amount_cents': targetCents,
      'current_amount': current,
      'current_amount_cents': currentCents,
      'progress_amount': current,
      'progress_amount_cents': currentCents,
      'consumed_amount': '\$0.00',
      'consumed_amount_cents': 0,
      'remaining_amount': '\$1,900.00',
      'remaining_amount_cents': 190000,
      'monthly_target_amount': '\$380.00',
      'monthly_target_amount_cents': 38000,
      'pace': '\$400.00',
      'pace_cents': 40000,
      'catch_up_amount': catchUp ?? '\$0.00',
      'catch_up_amount_cents': catchUpCents,
      'projection_end_amount': '\$5,300.00',
      'projection_end_amount_cents': 530000,
      'market_value': null,
      'market_value_cents': null,
      'progress_percent': progress,
      'progress_basis': 'balance',
      'months_of_runway': null,
      'projected_completion_date': '2027-03-01',
      'behind_pace': status == 'behind',
      'needs_attention': status == 'behind',
      'status_callout': callout,
      'currency_conversion_incomplete': false,
      'last_matched_pledge_date': null,
      'pledges_use_transfer': true,
      'pending_pledges_count': pledges.length,
      'open_pledges': pledges,
      'linked_account_count': (linked ?? [linkedJson('acc1')]).length,
      'linked_accounts': linked ?? [linkedJson('acc1')],
      'completed_at': null,
      'created_at': '2026-01-01T00:00:00Z',
      'updated_at': '2026-11-01T00:00:00Z',
    };

Map<String, dynamic> linkedJson(
  String id, {
  String name = 'Ally Savings',
  String? allocated,
  int? allocatedCents,
}) =>
    {
      'id': id,
      'name': name,
      'accountable_type': 'Depository',
      'currency': 'USD',
      'whole_account': allocated == null,
      'allocated_amount': allocated,
      'allocated_amount_cents': allocatedCents,
      'backing_amount': '\$3,100.00',
      'backing_amount_cents': 310000,
    };

Map<String, dynamic> pledgeJson(
  String id, {
  String amount = '\$150.00',
  String accountId = 'acc1',
  String? accountName = 'Ally Savings',
  String kind = 'transfer',
}) =>
    {
      'id': id,
      'account_id': accountId,
      'account_name': accountName,
      'kind': kind,
      'status': 'open',
      'amount': amount,
      'amount_cents': 15000,
      'currency': 'USD',
      'days_left': 6,
      'expires_at': '2026-11-20T12:00:00Z',
      'created_at': '2026-11-13T12:00:00Z',
    };

/// An account as `GET /api/v1/accounts` returns it.
Map<String, dynamic> accountJson(String id, String name, String type,
        {String balance = '\$3,100.00'}) =>
    {
      'id': id,
      'name': name,
      'balance': balance,
      'currency': 'USD',
      'classification': type == 'credit_card' ? 'liability' : 'asset',
      'account_type': type,
    };
